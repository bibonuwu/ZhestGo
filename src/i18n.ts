const MESSAGES: Record<Lang, Record<MessageKey, string>> = { kk, ru, en };

/** Each language's own name, for the language switchers. */
export const LANG_NAMES: Record<Lang, string> = { kk: 'Қазақша', ru: 'Русский', en: 'English' };
export const LANG_SHORT: Record<Lang, string> = { kk: 'ҚАЗ', ru: 'РУС', en: 'ENG' };
/** BCP 47 locale for dates and numbers. */
export const LOCALES: Record<Lang, string> = { kk: 'kk-KZ', ru: 'ru-RU', en: 'en-GB' };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const template = MESSAGES[lang][key] ?? MESSAGES.kk[key];
  return vars ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? '')) : template;
}

export function useT(): Translate {
  const lang = useSettings((s) => s.lang);
  return useCallback<Translate>((key, vars) => translate(lang, key, vars), [lang]);
}
